export let t: Messages = en;

export function setLanguage(language: Language) {
  const resolved = language === 'auto' ? (navigator.language.toLowerCase().startsWith('tr') ? 'tr' : 'en') : language;
  t = resolved === 'tr' ? tr : en;
  document.documentElement.lang = resolved;
}
